#include <iostream>

int main()
{
    int n, m, sum1=0, sum2=0;
    int arr1[5], arr2[5] ;
    std::cin >> n;
    for (int i=0; i<n; i++){
        std::cin >> arr1[i];
        sum1 += *(&arr1[i]);
    }
    for (int j = 0; j < n; j++) {
        std::cin >> arr2[j];
        sum2 += *(&arr2[j]);
    }
    if (sum1 >= sum2) {
        std::cout << "matrix [][] = { ";
        for (int i = 0; i < n; i++) {
            std::cout << arr1[i] << ' ';
        }
        for (int j = 0; j < n; j++) {
            std::cout << arr2[j] << ' ';
        }
        std::cout << "}";
    }
    if (sum1 < sum2) {
        std::cout << "matrix [][] = { ";
        for (int j = 0; j < n; j++) {
            std::cout << arr2[j] << ' ';
        }
        for (int i = 0; i < n; i++) {
            std::cout << arr1[i] << ' ';
        }
        std::cout << "}";
    }
    return 0;
}

